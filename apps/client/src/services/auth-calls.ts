import { z } from 'zod';
import {
  ROUTES,
  keyBundleDto,
  paramsResponse,
  recoveryStartResponse,
  sessionResponse,
  signInResponse,
  signUpResponse,
  userDto,
  type ParamsRequest,
  type RecoveryCompleteRequest,
  type RecoveryStartRequest,
  type SignInRequest,
  type SignUpRequest,
  passwordChangeResponse,
  deletionRequestResponse,
  type PasswordChangeRequest,
} from '@kodakiko/contract';
import type { ApiCall } from '../adapters/http/http';
import { RESTORE_TIMEOUT_MS, SIGN_OUT_TIMEOUT_MS } from '../constants/auth-constants';

export const AUTH_CALLS = Object.freeze({
  params: (body: ParamsRequest): ApiCall<z.infer<typeof paramsResponse>> => ({
    method: 'POST',
    path: ROUTES.authParams(),
    body,
    responseSchema: paramsResponse,
    auth: 'none',
    idempotent: true,
  }),
  signUp: (body: SignUpRequest): ApiCall<z.infer<typeof signUpResponse>> => ({
    method: 'POST',
    path: ROUTES.authSignUp(),
    body,
    responseSchema: signUpResponse,
    auth: 'none',
    idempotent: false,
  }),
  signIn: (body: SignInRequest): ApiCall<z.infer<typeof signInResponse>> => ({
    method: 'POST',
    path: ROUTES.authSignIn(),
    body,
    responseSchema: signInResponse,
    auth: 'none',
    idempotent: false,
  }),
  session: (): ApiCall<z.infer<typeof sessionResponse>> => ({
    method: 'GET',
    path: ROUTES.authSession(),
    responseSchema: sessionResponse,
    auth: 'session',
    idempotent: true,
    timeoutMs: RESTORE_TIMEOUT_MS,
  }),
  keyBundle: (): ApiCall<z.infer<typeof keyBundleDto>> => ({
    method: 'GET',
    path: ROUTES.authKeyBundle(),
    responseSchema: keyBundleDto,
    auth: 'session',
    idempotent: true,
  }),
  recoveryStart: (body: RecoveryStartRequest): ApiCall<z.infer<typeof recoveryStartResponse>> => ({
    method: 'POST',
    path: ROUTES.authRecoveryStart(),
    body,
    responseSchema: recoveryStartResponse,
    auth: 'none',
    idempotent: true,
  }),
  recoveryComplete: (body: RecoveryCompleteRequest): ApiCall<z.infer<typeof signInResponse>> => ({
    method: 'POST',
    path: ROUTES.authRecoveryComplete(),
    body,
    responseSchema: signInResponse,
    auth: 'none',
    idempotent: false,
  }),
  signOut: (): ApiCall<undefined> => ({
    method: 'POST',
    path: ROUTES.authSignOut(),
    responseSchema: z.undefined(),
    auth: 'session',
    idempotent: false,
    timeoutMs: SIGN_OUT_TIMEOUT_MS,
  }),
  changePassword: (body: PasswordChangeRequest): ApiCall<z.infer<typeof passwordChangeResponse>> => ({
    method: 'POST',
    path: ROUTES.authPassword(),
    body,
    responseSchema: passwordChangeResponse,
    auth: 'session',
    idempotent: false,
  }),
  requestDeletion: (): ApiCall<z.infer<typeof deletionRequestResponse>> => ({
    method: 'POST',
    path: ROUTES.usersMeDelete(),
    responseSchema: deletionRequestResponse,
    auth: 'session',
    idempotent: false,
  }),
  cancelDeletion: (): ApiCall<z.infer<typeof userDto>> => ({
    method: 'POST',
    path: ROUTES.usersMeDeleteCancel(),
    responseSchema: userDto,
    auth: 'session',
    idempotent: false,
  }),
});
