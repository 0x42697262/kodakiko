import { z } from 'zod';
import {
  ROUTES,
  collectionDto,
  diffPage,
  entryDto,
  mediaDto,
  objectDto,
  partsResponse,
  presignResponse,
  syncStateResponse,
  type EntryCreateRequest,
  type EntryPatchRequest,
  type MediaCreateRequest,
  type PresignRequest,
} from '@kodakiko/contract';
import type { ApiCall } from '../../adapters/http/http';

const anyBody = z.unknown();

export const SYNC_CALLS = Object.freeze({
  syncState: (): ApiCall<z.infer<typeof syncStateResponse>> => ({
    method: 'GET',
    path: ROUTES.syncState(),
    responseSchema: syncStateResponse,
    auth: 'session',
    idempotent: true,
  }),
  collection: (id: string): ApiCall<z.infer<typeof collectionDto>> => ({
    method: 'GET',
    path: ROUTES.collection(id),
    responseSchema: collectionDto,
    auth: 'session',
    idempotent: true,
  }),
  diff: (id: string, since: number, limit: number): ApiCall<z.infer<typeof diffPage>> => ({
    method: 'GET',
    path: `${ROUTES.collectionDiff(id)}?since=${since}&limit=${limit}`,
    responseSchema: diffPage,
    auth: 'session',
    idempotent: true,
  }),
  createEntry: (body: EntryCreateRequest): ApiCall<z.infer<typeof entryDto>> => ({
    method: 'POST',
    path: ROUTES.entries(),
    body,
    responseSchema: entryDto,
    auth: 'session',
    idempotent: true,
  }),
  getEntry: (id: string): ApiCall<z.infer<typeof entryDto>> => ({
    method: 'GET',
    path: ROUTES.entry(id),
    responseSchema: entryDto,
    auth: 'session',
    idempotent: true,
  }),
  patchEntry: (id: string, body: EntryPatchRequest): ApiCall<z.infer<typeof entryDto>> => ({
    method: 'PATCH',
    path: ROUTES.entry(id),
    body,
    responseSchema: entryDto,
    auth: 'session',
    idempotent: true,
  }),
  trashEntry: (id: string): ApiCall<z.infer<typeof entryDto>> => ({
    method: 'POST',
    path: ROUTES.entryTrash(id),
    responseSchema: entryDto,
    auth: 'session',
    idempotent: true,
  }),
  restoreEntry: (id: string): ApiCall<z.infer<typeof entryDto>> => ({
    method: 'POST',
    path: ROUTES.entryRestore(id),
    responseSchema: entryDto,
    auth: 'session',
    idempotent: true,
  }),
  deleteEntry: (id: string): ApiCall<unknown> => ({
    method: 'DELETE',
    path: ROUTES.entry(id),
    responseSchema: anyBody,
    auth: 'session',
    idempotent: true,
  }),
  addMedia: (entryId: string, body: MediaCreateRequest): ApiCall<z.infer<typeof mediaDto>> => ({
    method: 'POST',
    path: ROUTES.entryMedia(entryId),
    body,
    responseSchema: mediaDto,
    auth: 'session',
    idempotent: true,
  }),
  removeMedia: (mediaId: string): ApiCall<unknown> => ({
    method: 'DELETE',
    path: ROUTES.media(mediaId),
    responseSchema: anyBody,
    auth: 'session',
    idempotent: true,
  }),
  presign: (body: PresignRequest): ApiCall<z.infer<typeof presignResponse>> => ({
    method: 'POST',
    path: ROUTES.objectsPresign(),
    body,
    responseSchema: presignResponse,
    auth: 'session',
    idempotent: true,
  }),
  parts: (objectId: string): ApiCall<z.infer<typeof partsResponse>> => ({
    method: 'GET',
    path: ROUTES.objectParts(objectId),
    responseSchema: partsResponse,
    auth: 'session',
    idempotent: true,
  }),
  confirm: (objectId: string): ApiCall<z.infer<typeof objectDto>> => ({
    method: 'POST',
    path: ROUTES.objectConfirm(objectId),
    responseSchema: objectDto,
    auth: 'session',
    idempotent: true,
  }),
});
